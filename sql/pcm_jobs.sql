CREATE TABLE IF NOT EXISTS pcm_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    source_url TEXT NOT NULL,
    job_type TEXT NOT NULL DEFAULT 'download',
    destinations JSONB NOT NULL DEFAULT '["telegram"]'::jsonb,
    options JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued','running','paused','retrying','succeeded','failed','cancelled')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts INTEGER NOT NULL DEFAULT 3 CHECK (max_attempts >= 1),
    progress JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_error TEXT,
    worker_id TEXT,
    lease_until TIMESTAMPTZ,
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS pcm_jobs_owner_created_idx ON pcm_jobs (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS pcm_jobs_queue_idx ON pcm_jobs (status, created_at)
    WHERE status IN ('queued','retrying');
CREATE INDEX IF NOT EXISTS pcm_jobs_lease_idx ON pcm_jobs (lease_until)
    WHERE status = 'running';
