"""Durable PostgreSQL job queue primitives for PCM workers.

Jobs are persisted in InsForge PostgreSQL so a Colab runtime restart does not erase
queued work. The repository deliberately contains no Telegram or provider logic.
"""
from __future__ import annotations

import json
import os
from typing import Any

import asyncpg

_STATUSES = ("queued", "running", "paused", "retrying", "succeeded", "failed", "cancelled")
_TERMINAL = ("succeeded", "failed", "cancelled")
_SCHEMA = """
CREATE TABLE IF NOT EXISTS pcm_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    source_url TEXT NOT NULL,
    job_type TEXT NOT NULL DEFAULT 'download',
    destinations JSONB NOT NULL DEFAULT '[\"telegram\"]'::jsonb,
    options JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','running','paused','retrying','succeeded','failed','cancelled')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts INTEGER NOT NULL DEFAULT 3 CHECK (max_attempts >= 1),
    progress JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_error TEXT,
    worker_id TEXT,
    lease_until TIMESTAMPTZ,
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS pcm_jobs_owner_created_idx ON pcm_jobs (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS pcm_jobs_queue_idx ON pcm_jobs (status, created_at) WHERE status IN ('queued','retrying');
CREATE INDEX IF NOT EXISTS pcm_jobs_lease_idx ON pcm_jobs (lease_until) WHERE status = 'running';
"""


def _database_url() -> str:
    value = os.getenv("INSFORGE_DATABASE_URL", "").strip()
    if not value:
        raise RuntimeError("INSFORGE_DATABASE_URL is not configured.")
    return value


class JobRepository:
    """Persistent job state transitions backed by InsForge/PostgreSQL."""

    def __init__(self, database_url: str | None = None) -> None:
        self._database_url = database_url

    async def _connect(self) -> asyncpg.Connection:
        return await asyncpg.connect(self._database_url or _database_url(), ssl="require")

    async def ensure_schema(self) -> None:
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
        finally:
            await conn.close()

    async def enqueue(
        self,
        owner_id: int,
        source_url: str,
        *,
        job_type: str = "download",
        destinations: tuple[str, ...] | list[str] = ("telegram",),
        options: dict[str, Any] | None = None,
        max_attempts: int = 3,
    ) -> dict[str, Any]:
        url = source_url.strip()
        targets = list(dict.fromkeys(str(item).lower() for item in destinations))
        if not url or len(url) > 4096:
            raise ValueError("source_url must contain 1–4096 characters")
        if not targets or any(item not in {"telegram", "gofile"} for item in targets):
            raise ValueError("destinations must contain telegram and/or gofile")
        if not 1 <= max_attempts <= 10:
            raise ValueError("max_attempts must be between 1 and 10")
        if not job_type or len(job_type) > 40:
            raise ValueError("job_type must contain 1–40 characters")
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
            row = await conn.fetchrow(
                """INSERT INTO pcm_jobs (owner_id, source_url, job_type, destinations, options, max_attempts)
                   VALUES ($1, $2, $3, $4::jsonb, $5::jsonb, $6) RETURNING *""",
                owner_id, url, job_type, json.dumps(targets), json.dumps(options or {}), max_attempts,
            )
            return dict(row)
        finally:
            await conn.close()

    async def list_jobs(self, owner_id: int, *, limit: int = 10) -> list[dict[str, Any]]:
        if not 1 <= limit <= 50:
            raise ValueError("limit must be between 1 and 50")
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
            rows = await conn.fetch(
                "SELECT * FROM pcm_jobs WHERE owner_id=$1 ORDER BY created_at DESC LIMIT $2",
                owner_id, limit,
            )
            return [dict(row) for row in rows]
        finally:
            await conn.close()

    async def get_job(self, owner_id: int, job_id: int) -> dict[str, Any] | None:
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
            row = await conn.fetchrow("SELECT * FROM pcm_jobs WHERE owner_id=$1 AND id=$2", owner_id, job_id)
            return dict(row) if row else None
        finally:
            await conn.close()

    async def request_action(self, owner_id: int, job_id: int, action: str) -> dict[str, Any] | None:
        """Apply an owner-scoped state transition; running jobs observe cancel_requested."""
        if action not in {"cancel", "pause", "resume", "retry"}:
            raise ValueError("Unsupported job action")
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
            async with conn.transaction():
                row = await conn.fetchrow(
                    "SELECT * FROM pcm_jobs WHERE owner_id=$1 AND id=$2 FOR UPDATE", owner_id, job_id
                )
                if row is None:
                    return None
                status = row["status"]
                if action == "cancel":
                    if status in _TERMINAL:
                        raise ValueError(f"Job is already {status}")
                    if status == "running":
                        sql = "UPDATE pcm_jobs SET cancel_requested=TRUE, updated_at=NOW() WHERE id=$1 RETURNING *"
                    else:
                        sql = "UPDATE pcm_jobs SET status='cancelled', cancel_requested=TRUE, finished_at=NOW(), updated_at=NOW() WHERE id=$1 RETURNING *"
                    updated = await conn.fetchrow(sql, job_id)
                elif action == "pause":
                    if status not in {"queued", "retrying"}:
                        raise ValueError("Only queued jobs can be paused in this version")
                    updated = await conn.fetchrow("UPDATE pcm_jobs SET status='paused', updated_at=NOW() WHERE id=$1 RETURNING *", job_id)
                elif action == "resume":
                    if status != "paused":
                        raise ValueError("Only paused jobs can be resumed")
                    updated = await conn.fetchrow("UPDATE pcm_jobs SET status='queued', updated_at=NOW() WHERE id=$1 RETURNING *", job_id)
                else:
                    if status not in {"failed", "cancelled"}:
                        raise ValueError("Only failed or cancelled jobs can be retried")
                    updated = await conn.fetchrow(
                        "UPDATE pcm_jobs SET status='queued', attempts=0, last_error=NULL, cancel_requested=FALSE, worker_id=NULL, lease_until=NULL, finished_at=NULL, updated_at=NOW() WHERE id=$1 RETURNING *",
                        job_id,
                    )
                return dict(updated)
        finally:
            await conn.close()

    async def claim_next(self, worker_id: str, *, lease_seconds: int = 300) -> dict[str, Any] | None:
        """Atomically claim one queued job; SKIP LOCKED allows multiple workers safely."""
        if not worker_id or len(worker_id) > 128:
            raise ValueError("worker_id must contain 1–128 characters")
        if not 15 <= lease_seconds <= 3600:
            raise ValueError("lease_seconds must be between 15 and 3600")
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
            async with conn.transaction():
                row = await conn.fetchrow(
                    """SELECT id FROM pcm_jobs
                       WHERE status IN ('queued','retrying') AND cancel_requested=FALSE
                       ORDER BY created_at ASC LIMIT 1 FOR UPDATE SKIP LOCKED"""
                )
                if row is None:
                    return None
                claimed = await conn.fetchrow(
                    """UPDATE pcm_jobs SET status='running', worker_id=$2,
                       attempts=attempts+1, started_at=COALESCE(started_at,NOW()),
                       lease_until=NOW()+($3 * INTERVAL '1 second'), updated_at=NOW()
                       WHERE id=$1 RETURNING *""",
                    row["id"], worker_id, lease_seconds,
                )
                return dict(claimed)
        finally:
            await conn.close()

    async def heartbeat(self, job_id: int, worker_id: str, *, lease_seconds: int = 300,
                        progress: dict[str, Any] | None = None) -> bool:
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
            result = await conn.execute(
                """UPDATE pcm_jobs SET lease_until=NOW()+($3 * INTERVAL '1 second'),
                   progress=COALESCE($4::jsonb, progress), updated_at=NOW()
                   WHERE id=$1 AND worker_id=$2 AND status='running' AND cancel_requested=FALSE""",
                job_id, worker_id, lease_seconds, json.dumps(progress) if progress is not None else None,
            )
            return result.endswith("1")
        finally:
            await conn.close()

    async def finish(self, job_id: int, worker_id: str, *, error: str | None = None) -> str:
        """Mark a job successful or retry/fail it according to its attempt budget."""
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
            async with conn.transaction():
                row = await conn.fetchrow(
                    "SELECT status, attempts, max_attempts, cancel_requested FROM pcm_jobs WHERE id=$1 AND worker_id=$2 FOR UPDATE",
                    job_id, worker_id,
                )
                if row is None:
                    raise ValueError("Job lease not found or no longer owned by this worker")
                if row["cancel_requested"]:
                    status, finished = "cancelled", "NOW()"
                elif error is None:
                    status, finished = "succeeded", "NOW()"
                elif row["attempts"] < row["max_attempts"]:
                    status, finished = "retrying", "NULL"
                else:
                    status, finished = "failed", "NOW()"
                await conn.execute(
                    f"""UPDATE pcm_jobs SET status=$2, last_error=$3, worker_id=NULL,
                        lease_until=NULL, finished_at={finished}, updated_at=NOW() WHERE id=$1""",
                    job_id, status, error[:2000] if error else None,
                )
                return status
        finally:
            await conn.close()

    async def recover_expired(self) -> int:
        """Recover abandoned running jobs after a Colab/runtime restart."""
        conn = await self._connect()
        try:
            await conn.execute(_SCHEMA)
            result = await conn.execute(
                """UPDATE pcm_jobs SET
                   status=CASE WHEN cancel_requested THEN 'cancelled'
                               WHEN attempts < max_attempts THEN 'retrying' ELSE 'failed' END,
                   last_error=COALESCE(last_error, 'Worker lease expired; recovered after restart'),
                   worker_id=NULL, lease_until=NULL,
                   finished_at=CASE WHEN cancel_requested OR attempts >= max_attempts THEN NOW() ELSE NULL END,
                   updated_at=NOW()
                   WHERE status='running' AND lease_until < NOW()"""
            )
            return int(result.rsplit(" ", 1)[-1])
        finally:
            await conn.close()
